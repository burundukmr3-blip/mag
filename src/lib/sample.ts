export function createSampleGame(): Game {
  const now = Date.now();
  const rounds: Round[] = ROUNDS.map((r, ri) => {
    const values = defaultValues(ri);
    return {
      id: uid(),
      name: r.name,
      values,
      themes: r.themes.map(([name, qs]) => ({
        id: uid(),
        name,
        questions: qs.map(([text, answer, comment = '', extra], qi) => newQuestion(values[qi], { text, answer, comment, ...extra })),
      })),
    };
  });
  return {
    id: uid(),
    name: 'Осень и Хэллоуин',
    createdAt: now,
    updatedAt: now,
    rounds,
    final: FINAL.map(([theme, text, answer, comment = '']) => ({ ...newFinalQuestion(theme), text, answer, comment })),
    settings: defaultGameSettings(),
  };
}
